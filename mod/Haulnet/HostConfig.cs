using System.Text;

namespace Haulnet;

/// <summary>
/// LuxonServer's <c>config.yml</c> for Host mode. Kept free of game types so the exact text can be tested without
/// the game; every key must be one LuxonServer accepts, or it refuses to start.
/// </summary>
internal static class HostConfig
{
    /// <summary>
    /// The only region the host server offers (LuxonServer name "europe", Photon code "eu",
    /// <see cref="HostServer.RegionCode"/>). The name has no meaning for a server on the host's PC; it only has to match.
    /// </summary>
    public const string RegionName = "europe";

    /// <summary>
    /// Only the ports the game uses are opened: NameServer on <paramref name="basePort"/>, MasterServer and GameServer
    /// on the next two. The advertised address is loopback: the host's own game uses it as is, and joining players
    /// rewrite it to the address they used (see PhotonRedirect). A single region keeps the game's region page short.
    /// </summary>
    public static string Build(int basePort)
    {
        var names = new[] { "NameServer", "MasterServer", "GameServer" };
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by Haulnet for Host mode. Changes are overwritten on every start.");
        sb.AppendLine("Servers:");
        for (var i = 0; i < names.Length; i++)
        {
            sb.AppendLine($"  {names[i]}:");
            sb.AppendLine($"    - port: {basePort + i}");
            sb.AppendLine($"      external_address: 127.0.0.1:{basePort + i}");
        }

        sb.AppendLine("EnableIPv6: true");
        sb.AppendLine("MaxConnections: 20");
        sb.AppendLine("MaxGamePeers: 0");
        sb.AppendLine("TickTimeBudget: 2000");
        sb.AppendLine("NoBanner: true");
        sb.AppendLine("Regions:");
        sb.AppendLine("  - " + RegionName);
        sb.AppendLine("HTTP:");
        sb.AppendLine("  enabled: false");
        return sb.ToString();
    }
}
